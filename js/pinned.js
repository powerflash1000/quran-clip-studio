// كل الاقتراحات المناسبة للريل (الأنسب الأول)
export function pinnedOptions(blocks) {
  const out = [];
  for (const b of blocks.filter(x => x.type === 'quran')) {
    for (const q of QURAN) if (q.test(b.surah, b.from, b.to || b.from)) out.push(...q.list.map(x => ({ ...x, why: `سورة ${Q.surah(b.surah).ar}` })));
  }
  const text = blocks.filter(x => x.type !== 'quran').map(x => x.text || '').join(' ').replace(/[ً-ْٰ]/g, '');
  for (const t of TOPICS) if (t.rx.test(text)) out.push(...t.list.map(x => ({ ...x, why: 'محتوى الدعاء' })));
  out.push(...GENERAL.map(x => ({ ...x, why: 'عام' })));
  const seen = new Set();
  return out.filter(x => !seen.has(x.text) && seen.add(x.text));
}

